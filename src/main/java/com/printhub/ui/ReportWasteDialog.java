    private final PrintHubData data = PrintHubData.get();

    public ReportWasteDialog(java.awt.Window owner, JobOrder preselected) {
        super(owner, "Report Waste / Paper Jam", ModalityType.APPLICATION_MODAL);
        initComponents();

        for (Supply s : data.supplies()) {
            itemBox.addItem(s);
        }
        jobBox.addItem("None");
        JobOrder pick = null;
        for (JobOrder j : data.allJobs()) {
            jobBox.addItem(j);
            if (preselected != null && j.getId().equals(preselected.getId())) {
                pick = j;
            }
        }
        if (pick != null) {
            jobBox.setSelectedItem(pick);
        }

        cancelButton.addActionListener(e -> dispose());
        saveButton.addActionListener(e -> save());
        itemBox.addActionListener(e -> updateInfo());
        qtySpinner.addChangeListener(e -> updateInfo());
        updateInfo();
        setLocationRelativeTo(owner);
    }

    private void updateInfo() {
        Supply s = (Supply) itemBox.getSelectedItem();
        int q = (Integer) qtySpinner.getValue();
        String unit = s == null ? "" : s.getUnit();
        infoLabel.setText("<html>Stock for this item will be reduced by " + q + " " + unit
                + " and the<br>record will appear in the Waste Log.</html>");
    }

    private void save() {
        Supply s = (Supply) itemBox.getSelectedItem();
        if (s == null) {
            return;
        }
        Object related = jobBox.getSelectedItem();
        String jobId = related instanceof JobOrder ? ((JobOrder) related).getId() : null;
        try {
            data.recordWaste(s, (Integer) qtySpinner.getValue(), (WasteReason) reasonBox.getSelectedItem(), jobId);
            dispose();
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Cannot record waste", JOptionPane.WARNING_MESSAGE);
        }
    }

