    private void signIn() {
        Account account = PrintHubData.get().authenticate(usernameField.getText().trim(),
                new String(passwordField.getPassword()));
        if (account == null) {
            errorLabel.setText("Wrong username or password.");
            passwordField.selectAll();
            passwordField.requestFocusInWindow();
            return;
        }
        dispose();
        // Logout closes the main window and shows a fresh login screen
        new MainFrame(account, () -> new LoginFrame().setVisible(true)).setVisible(true);
    }

