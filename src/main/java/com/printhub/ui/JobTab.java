    private static final String[] COLUMNS = {"Queue #", "Job ID", "Customer", "Service", "Size",
        "Pages " + Ui.TIMES + " Copies", "Priority", "Time Received", "Status", "Payment"};

    private final DefaultTableModel model = Tables.model(COLUMNS);
    private final boolean pending;

    /** @param pending true for the Pending tab: shows the banner and tints the first row. */
    public JobTab(boolean pending) {
        this.pending = pending;
        initComponents();
        banner.removeAll(); // the form shows a sample banner; showNext fills the real one
        table.setModel(model);
        Tables.prepare(table, new int[] {}, new int[] {6, 8, 9}, pending);
        Tables.widths(table, 70, 100, 170, 140, 70, 110, 100, 120, 110, 90);
        banner.setLayout(new FlowLayout(FlowLayout.LEFT, 8, 9));
        bannerWrap.setVisible(pending);
    }

    public JTable getTable() {
        return table;
    }

    public void load(List<JobOrder> jobs, boolean numbered) {
        model.setRowCount(0);
        int n = 1;
        for (JobOrder j : jobs) {
            model.addRow(new Object[] {
                numbered ? String.valueOf(n++) : Ui.DASH,
                j.getId(), j.getSource() == JobSource.ONLINE ? j.getCustomer() + " (Online)" : j.getCustomer(),
                j.getDetail() == null ? j.getService().label()
                        : j.getService().label() + " " + Ui.DOT + " " + j.getDetail(),
                j.getSize().label(), j.pagesCopies(),
                j.isRush() ? "Rush" : "Normal", j.getReceived().format(Ui.TIME), j.getStatus().label(),
                j.getPaymentStatus().label()});
        }
    }

    /** "Next to process JOB-0231 ..." banner; pass null when the queue is empty. */
    public void showNext(JobOrder next) {
        if (!pending) {
            return;
        }
        banner.removeAll();
        if (next == null) {
            banner.add(Ui.label("No pending jobs. The queue is empty.", FONT_BODY, TEXT_SECONDARY));
        } else {
            banner.add(Ui.triangle(ACCENT));
            banner.add(Ui.label("Next to process", FONT_BODY_BOLD, ACCENT));
            banner.add(Ui.body(next.getId() + " " + Ui.DOT + " " + next.getCustomer() + " " + Ui.DOT + " "
                    + next.getService().label() + " " + Ui.DOT + " " + next.getSize().label() + " " + Ui.DOT + " "
                    + next.getPages() + " pages " + Ui.TIMES + " " + next.getCopies() + " copies"));
            if (next.isRush()) {
                banner.add(PrintHubTheme.badge("Rush"));
            }
        }
        banner.revalidate();
        banner.repaint();
    }

