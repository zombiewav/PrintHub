    public SupplyDialog(java.awt.Window owner, Supply editing) {
        super(owner, editing == null ? "Add Supply" : "Edit Supply", ModalityType.APPLICATION_MODAL);
        this.editing = editing;
        initComponents();
        statusHolder.setLayout(new FlowLayout(FlowLayout.LEFT, 0, 0));

        if (editing == null) {
            idField.setText(data.newSupplyId());
        } else {
            idField.setText(editing.getId());
            categoryBox.setSelectedItem(editing.getCategory());
            nameField.setText(editing.getName());
            sizeBox.setSelectedItem(editing.getSize());
            unitBox.setSelectedItem(editing.getUnit());
            stockSpinner.setValue(editing.getStock());
            reorderSpinner.setValue(editing.getReorderLevel());
        }

        cancelButton.addActionListener(e -> dispose());
        saveButton.addActionListener(e -> save());
        stockSpinner.addChangeListener(e -> updateStatus());
        reorderSpinner.addChangeListener(e -> updateStatus());
        updateStatus();
        setLocationRelativeTo(owner);
    }

    private void updateStatus() {
        int s = (Integer) stockSpinner.getValue();
        int r = (Integer) reorderSpinner.getValue();
        String text = s <= 0 ? "Out" : (s <= r ? "Low" : "OK");
        statusHolder.removeAll();
        statusHolder.add(PrintHubTheme.badge(text));
        statusHolder.revalidate();
        statusHolder.repaint();
    }

    private void save() {
        String n = nameField.getText().trim();
        if (n.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter the item name.", "Cannot save", JOptionPane.WARNING_MESSAGE);
            nameField.requestFocusInWindow();
            return;
        }
        if (editing == null) {
            data.addSupply(new Supply(idField.getText(), n, (String) categoryBox.getSelectedItem(),
                    (String) sizeBox.getSelectedItem(), (String) unitBox.getSelectedItem(),
                    (Integer) stockSpinner.getValue(), (Integer) reorderSpinner.getValue()));
        } else {
            editing.setName(n);
            editing.setCategory((String) categoryBox.getSelectedItem());
            editing.setSize((String) sizeBox.getSelectedItem());
            editing.setUnit((String) unitBox.getSelectedItem());
            editing.setStock((Integer) stockSpinner.getValue());
            editing.setReorderLevel((Integer) reorderSpinner.getValue());
            data.changed();
        }
        dispose();
    }

