    private void reset() {
        fromSpinner.setValue(toDate(LocalDate.now()));
        toSpinner.setValue(toDate(LocalDate.now()));
        methodBox.setSelectedIndex(0);
        refresh();
    }

    private static Date toDate(LocalDate d) {
        return Date.from(d.atStartOfDay(ZoneId.systemDefault()).toInstant());
    }

    private static LocalDate toLocal(Object value) {
        return ((Date) value).toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    @Override
    public void refresh() {
        LocalDate start = toLocal(fromSpinner.getValue());
        LocalDate end = toLocal(toSpinner.getValue());
        Object selected = methodBox.getSelectedItem();

        model.setRowCount(0);
        double total = 0;
        double cash = 0;
        double gcash = 0;
        int cashCount = 0;
        int gcashCount = 0;
        for (Transaction t : data.transactions()) {
            LocalDate day = t.getDateTime().toLocalDate();
            if (day.isBefore(start) || day.isAfter(end)) {
                continue;
            }
            if (selected instanceof PaymentMethod && t.getMethod() != selected) {
                continue;
            }
            total += t.getAmount();
            if (t.getMethod() == PaymentMethod.CASH) {
                cash += t.getAmount();
                cashCount++;
            } else {
                gcash += t.getAmount();
                gcashCount++;
            }
            model.addRow(new Object[] {t.getId(), t.getDateTime().format(Ui.DAY_TIME), t.getCustomer(), t.getJobId(),
                Ui.money(t.getAmount()), t.getMethod().label(),
                t.getReference() == null ? Ui.DASH : t.getReference()});
        }

        int cashPct = total == 0 ? 0 : (int) Math.round(cash * 100 / total);
        int gcashPct = total == 0 ? 0 : 100 - cashPct;
        rangeLabel.setText(start.format(Ui.SHORT_DATE) + " " + Ui.ENDASH + " " + end.format(Ui.SHORT_DATE));
        totalValue.setText(Ui.money(total));
        totalNote.setText((cashCount + gcashCount) + " transactions");
        cashValue.setText(Ui.money(cash));
        cashNote.setText(cashCount + " transactions " + Ui.DOT + " " + cashPct + "%");
        gcashValue.setText(Ui.money(gcash));
        gcashNote.setText(gcashCount + " transactions " + Ui.DOT + " " + gcashPct + "%");
    }

