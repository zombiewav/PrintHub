    /** Number of waste records, for the tab chip. */
    public int getTotal() {
        return data.wasteLog().size();
    }

    public void refresh() {
        int reasonIndex = reasonBox.getSelectedIndex();
        int period = periodBox.getSelectedIndex();
        LocalDate today = LocalDate.now();
        LocalDate from = period == 0 ? today.minusDays(6) : period == 1 ? today.minusDays(29) : LocalDate.MIN;

        model.setRowCount(0);
        int[] byReason = new int[3];
        int records = 0;
        int items = 0;
        for (WasteRecord w : data.wasteLog()) {
            if (w.getDateTime().toLocalDate().isBefore(from)) {
                continue;
            }
            if (reasonIndex > 0 && w.getReason().ordinal() != reasonIndex - 1) {
                continue;
            }
            records++;
            items += w.getQty();
            byReason[w.getReason().ordinal()] += w.getQty();
            model.addRow(new Object[] {w.getDateTime().format(Ui.FULL_STAMP), w.getSupply().displayName(),
                w.qtyText(), w.getReason().label(), w.getJobId() == null ? Ui.DASH : w.getJobId()});
        }
        totalLabel.setText("Total wasted: " + items + " items");
        footerLabel.setText(records + " records " + Ui.DOT + " Paper Jam " + byReason[WasteReason.PAPER_JAM.ordinal()]
                + " " + Ui.DOT + " Misprint " + byReason[WasteReason.MISPRINT.ordinal()]
                + " " + Ui.DOT + " Damaged " + byReason[WasteReason.DAMAGED.ordinal()]);
    }

